const pick = (rand, list) => {
  const [text, from] = list[randInt(rand, list.length)]
  return { text, from }
}

// level：当日一签的吉凶；hl：huangli() 的返回值
export function dailySaying(rand, level, hl) {
  const keys = [hl?.jieqi?.today ? hl.jieqi.name : '', ...(hl?.festivals || [])]
  for (const k of keys) {
    if (k && SEASONAL[k]) {
      const [text, from] = SEASONAL[k]
      return { text, from, occasion: k }
    }
  }
  const pool = level === '上上' || level === '上' ? GOOD : level === '中' ? MID : level ? GENTLE : MID
  return pick(rand, pool)
}
